// What people see of a documented live product never names an internal codename, a benchmark product the team
// compares against, or the AI that wrote it. Two kinds of words:
//   - internal terms: the engine host's private terms (MF_PRIVATE_TERMS_FILE, the same list the engine's privacy guard
//     scrubs every write with: server/blocks/engineWorker/privacy.ts), the engine's built-in codenames (the list the
//     builds of existing products keep out of the code: official/neutral.ts) and the benchmark products. A text is
//     cleaned (a parenthesis that names one goes, then the name itself), and an item a model wrote that named one is
//     dropped as a whole (it was about the internal thing);
//   - AI wording ("AI", "Claude", "generated by"…): an item that uses it is dropped.
// Pure apart from reading the host's term list.
import { privateTermsPattern } from "../../../../blocks/engineWorker/privacy.ts";
import { CODENAMES } from "../../official/neutral.ts";

/** The products the team benchmarks the product against: the comparison is internal planning, never the product's
 *  own record. */
export const BENCHMARKS: readonly string[] = ["Zoho", "Odoo"];

/** Names internal to the team's planning that never reach the product's records: the engine's built-in codenames
 *  (official/neutral.ts; owner's rule 08.11.2026: nothing user-facing names AGIS) and the benchmark products. */
export const INTERNAL_TERMS: readonly string[] = [...CODENAMES, ...BENCHMARKS];

const AI_WORDS = /\b(?:A\.?I\.?(?=[\s,.;:)!?]|$)|artificial intelligence|machine learning|Claude|Anthropic|ChatGPT|OpenAI|GPT(?:-?\d[\w.]*)?|LLMs?|large language model|language model|Codex|Copilot|Gemini|generated by|auto-?generated)\b/i;

const escape = (t: string) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** The internal terms of this host as one pattern (word-bounded, any case). */
export function internalPattern(env: NodeJS.ProcessEnv = process.env, extra: readonly string[] = []): RegExp {
  const host = privateTermsPattern(env);
  const own = [...INTERNAL_TERMS, ...extra].filter((t) => t.trim().length >= 2).map((t) => `\\b${escape(t.trim())}\\b`);
  const parts = [...own, ...(host ? [`(?:${host.source})`] : [])];
  return new RegExp(parts.join("|"), "gi");
}

export interface Terms {
  /** True when the text names an internal term. */
  internal(text: string): boolean;
  /** True when the text uses AI wording. */
  ai(text: string): boolean;
  /** The text without any internal term: a parenthesis or bracket naming one is removed, then the term itself (with a
   *  following colon or possessive), and the spacing and punctuation are tidied. */
  clean(text: string): string;
}

export function termsOf(env: NodeJS.ProcessEnv = process.env, extra: readonly string[] = []): Terms {
  const re = internalPattern(env, extra);
  const test = (t: string) => {
    re.lastIndex = 0;
    return re.test(t);
  };
  return {
    internal: test,
    ai: (t) => AI_WORDS.test(t),
    clean(text) {
      if (!test(text)) return text;
      let out = text.replace(/\s*[([{][^()[\]{}]*[)\]}]/g, (m) => (test(m) ? "" : m));
      re.lastIndex = 0;
      out = out.replace(new RegExp(`(?:${re.source})(?:'s|:)?`, "gi"), "");
      return out
        .replace(/\s{2,}/g, " ")
        .replace(/\s+([,.;:!?)])/g, "$1")
        .replace(/\(\s*\)/g, "")
        .replace(/^[\s,.;:–—-]+|[\s,;:–—-]+$/g, "")
        .trim();
    },
  };
}

/** A model's text item, or null when it names an internal term or uses AI wording (the whole item goes). */
export function keepItem(terms: Terms, text: string | null): string | null {
  if (text === null) return null;
  return terms.internal(text) || terms.ai(text) ? null : text;
}
