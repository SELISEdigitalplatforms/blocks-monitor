/**
 * Registry Writer — generates and updates MADP project registry YAML files.
 *
 * Maps frontend project data to `engine/selise-madp/MADP/projects/<name>.yml`.
 */
import { writeFileSync, mkdirSync, existsSync, readFileSync, unlinkSync } from "node:fs";
import { join } from "node:path";
import { paths } from "./engineBridge.ts";

export interface ProjectData {
  id: string;
  name: string;
  description: string;
  kind: "new" | "existing";
  repoUrl: string;
  repoBranch: string;
  repoPath?: string;
  repoRole?: "web" | "api" | "other";
  gitAuthorName: string;
  gitAuthorEmail: string;
  defaultEnv?: string;
  blocksProjectRef?: string;
  profile?: string;
  deploy?: boolean;
}

/** Write a project registry YAML file. Returns the file path. */
export function writeRegistry(data: ProjectData): string {
  mkdirSync(paths.projectsDir, { recursive: true });

  const slug = data.name.toLowerCase().replace(/[^a-z0-9-]/g, "-").replace(/-+/g, "-");
  const filePath = join(paths.projectsDir, `${slug}.yml`);

  // Parse GitHub org/repo from URL
  const ghMatch = data.repoUrl.match(/github\.com[/:]([^/]+\/[^/.]+)/);
  const ghRepo = ghMatch ? ghMatch[1].replace(/\.git$/, "") : "";

  const env = data.defaultEnv || "dev";
  const role = data.repoRole || "web";
  const profile = data.profile || "selise-blocks-app";
  const tenant = data.blocksProjectRef?.trim() || "";
  if (tenant && !/^D[0-9a-f]{32}$/i.test(tenant)) throw new Error("invalid_blocks_project_id");
  const deploy = data.deploy ?? Boolean(tenant);

  const yaml = `# Auto-generated by MADP Factory frontend
# Edit via the Factory UI or madp project check ${slug}
project: ${slug}
description: ${JSON.stringify(data.description)}
standards: {profile: ${profile}}
default_env: ${env}
environments:
  ${env}: {branch: ${data.repoBranch || env}${tenant ? `, tenant_id: ${JSON.stringify(tenant)}` : ""}}
deploy: ${deploy}
git:
  author_name: ${data.gitAuthorName}
  author_email: ${data.gitAuthorEmail}
repos:
  ${role}:
    path: ${data.repoPath || ""}
    repo: ${ghRepo}
    branch: ${data.repoBranch || env}
    role: ${role}
    verify:
      - name: typecheck
        argv: [npm, run, typecheck]
      - name: build
        argv: [npm, run, build]
    health: []
`;

  writeFileSync(filePath, yaml, "utf-8");

  // Also ensure the artifacts directory exists
  const projectId = slug.toUpperCase();
  mkdirSync(join(paths.artifactsDir, projectId), { recursive: true });
  mkdirSync(join(paths.artifactsDir, projectId, "specs"), { recursive: true });

  return filePath;
}

/** Sync registry YAML directly from a database Project row. */
export function syncProjectRegistry(project: Record<string, unknown>, repoPath = ""): string | null {
  const name = typeof project.Name === "string" ? project.Name.trim() : "";
  if (!name) return null;
  const tenant = typeof project.BlocksProjectRef === "string" && /^D[0-9a-f]{32}$/i.test(project.BlocksProjectRef) ? project.BlocksProjectRef : undefined;
  const owner = typeof project.RepoOwner === "string" ? project.RepoOwner.trim() : "";
  const repoName = typeof project.RepoName === "string" ? project.RepoName.trim() : "";
  const repoUrl = owner && repoName ? `https://github.com/${owner}/${repoName}` : "";
  const repoBranch = typeof project.RepoBranch === "string" && project.RepoBranch.trim() ? project.RepoBranch.trim() : "dev";
  return writeRegistry({
    id: String(project.ItemId || name),
    name,
    description: typeof project.Goal === "string" ? project.Goal : "",
    kind: project.RepoMode === "existing" ? "existing" : "new",
    repoUrl,
    repoBranch,
    repoPath,
    blocksProjectRef: tenant,
    gitAuthorName: "MADP Factory",
    gitAuthorEmail: "factory@selise.ch",
    deploy: Boolean(tenant),
  });
}

/** Read a project registry YAML as raw text. */
export function readRegistry(name: string): string | null {
  const slug = name.toLowerCase().replace(/[^a-z0-9-]/g, "-");
  const filePath = join(paths.projectsDir, `${slug}.yml`);
  if (!existsSync(filePath)) return null;
  return readFileSync(filePath, "utf-8");
}

/** Delete a project registry YAML. */
export function deleteRegistry(name: string): boolean {
  const slug = name.toLowerCase().replace(/[^a-z0-9-]/g, "-");
  const filePath = join(paths.projectsDir, `${slug}.yml`);
  if (!existsSync(filePath)) return false;
  unlinkSync(filePath);
  return true;
}
